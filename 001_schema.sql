-- Emenda Clara - esquema inicial PostgreSQL
-- Executar em um banco vazio criado para este sistema.
-- A aplicação deve conectar com usuário de banco sem privilégios de proprietário.

CREATE SCHEMA IF NOT EXISTS emenda_clara;
SET search_path TO emenda_clara, public;

CREATE TABLE IF NOT EXISTS usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador_autenticacao text NOT NULL UNIQUE,
    nome_exibicao text NOT NULL,
    email text,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS usuario_perfis (
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    perfil text NOT NULL CHECK (perfil IN ('administrador', 'gestao_publica', 'fazenda', 'controle')),
    concedido_em timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (usuario_id, perfil)
);
CREATE INDEX IF NOT EXISTS usuario_perfis_perfil_idx ON usuario_perfis (perfil, usuario_id);

CREATE TABLE IF NOT EXISTS vereadores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo text NOT NULL,
    inicio_mandato date,
    fim_mandato date,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    CHECK (fim_mandato IS NULL OR inicio_mandato IS NULL OR fim_mandato >= inicio_mandato)
);
CREATE INDEX IF NOT EXISTS vereadores_nome_idx ON vereadores (nome_completo);

CREATE TABLE IF NOT EXISTS gabinetes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo text NOT NULL UNIQUE,
    nome text NOT NULL,
    vereador_id bigint REFERENCES vereadores(id) ON DELETE RESTRICT,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    UNIQUE (vereador_id)
);
CREATE INDEX IF NOT EXISTS gabinetes_vereador_id_idx ON gabinetes (vereador_id);

CREATE TABLE IF NOT EXISTS gabinete_usuarios (
    gabinete_id bigint NOT NULL REFERENCES gabinetes(id) ON DELETE RESTRICT,
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    papel text NOT NULL CHECK (papel IN ('gestor', 'editor', 'consulta')),
    ativo boolean NOT NULL DEFAULT true,
    concedido_em timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (gabinete_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS gabinete_usuarios_usuario_idx ON gabinete_usuarios (usuario_id, ativo);

CREATE TABLE IF NOT EXISTS secretarias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_externo text UNIQUE,
    nome text NOT NULL UNIQUE,
    origem_cadastro text NOT NULL DEFAULT 'a confirmar',
    confirmado_em timestamptz,
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS secretarias_ativas_nome_idx ON secretarias (nome) WHERE ativo;

CREATE TABLE IF NOT EXISTS secretaria_usuarios (
    secretaria_id bigint NOT NULL REFERENCES secretarias(id) ON DELETE RESTRICT,
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    papel text NOT NULL CHECK (papel IN ('gestor', 'analista', 'consulta')),
    ativo boolean NOT NULL DEFAULT true,
    concedido_em timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (secretaria_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS secretaria_usuarios_usuario_idx ON secretaria_usuarios (usuario_id, ativo);

CREATE TABLE IF NOT EXISTS emendas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_protocolo text UNIQUE,
    exercicio smallint NOT NULL CHECK (exercicio >= 2000),
    gabinete_id bigint NOT NULL REFERENCES gabinetes(id) ON DELETE RESTRICT,
    vereador_id bigint REFERENCES vereadores(id) ON DELETE RESTRICT,
    secretaria_id bigint REFERENCES secretarias(id) ON DELETE RESTRICT,
    titulo text NOT NULL,
    objeto text NOT NULL,
    justificativa text,
    beneficiario text,
    localidade text,
    valor_solicitado numeric(14,2) NOT NULL CHECK (valor_solicitado > 0),
    aplicacao text CHECK (aplicacao IN ('custeio', 'investimento')),
    status text NOT NULL DEFAULT 'rascunho' CHECK (status IN (
        'rascunho', 'enviada', 'em_analise', 'devolvida_para_ajustes',
        'aprovada', 'nao_aprovada', 'em_execucao', 'pagamento_parcial',
        'paga', 'encerrada', 'cancelada'
    )),
    criada_por_usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    atualizada_por_usuario_id bigint REFERENCES usuarios(id) ON DELETE RESTRICT,
    criada_em timestamptz NOT NULL DEFAULT now(),
    atualizada_em timestamptz NOT NULL DEFAULT now(),
    enviada_em timestamptz
);
CREATE INDEX IF NOT EXISTS emendas_gabinete_exercicio_idx ON emendas (gabinete_id, exercicio DESC, criada_em DESC);
CREATE INDEX IF NOT EXISTS emendas_secretaria_status_idx ON emendas (secretaria_id, status) WHERE secretaria_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS emendas_vereador_exercicio_idx ON emendas (vereador_id, exercicio DESC) WHERE vereador_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS emendas_status_atualizada_idx ON emendas (status, atualizada_em DESC);
CREATE INDEX IF NOT EXISTS emendas_criador_idx ON emendas (criada_por_usuario_id);
CREATE INDEX IF NOT EXISTS emendas_atualizador_idx ON emendas (atualizada_por_usuario_id) WHERE atualizada_por_usuario_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS emenda_documentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emenda_id bigint NOT NULL REFERENCES emendas(id) ON DELETE RESTRICT,
    chave_armazenamento text NOT NULL UNIQUE,
    nome_arquivo text NOT NULL,
    tipo_mime text,
    tamanho_bytes bigint CHECK (tamanho_bytes IS NULL OR tamanho_bytes >= 0),
    enviado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    enviado_em timestamptz NOT NULL DEFAULT now(),
    descricao text
);
CREATE INDEX IF NOT EXISTS emenda_documentos_emenda_idx ON emenda_documentos (emenda_id, enviado_em DESC);
CREATE INDEX IF NOT EXISTS emenda_documentos_usuario_idx ON emenda_documentos (enviado_por_usuario_id);

CREATE TABLE IF NOT EXISTS emenda_historico (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emenda_id bigint NOT NULL REFERENCES emendas(id) ON DELETE RESTRICT,
    usuario_id bigint REFERENCES usuarios(id) ON DELETE RESTRICT,
    evento text NOT NULL CHECK (evento IN (
        'criada', 'editada', 'enviada', 'em_analise', 'devolvida', 'aprovada',
        'nao_aprovada', 'em_execucao', 'pagamento_atualizado', 'encerrada',
        'cancelada', 'documento_anexado', 'observacao'
    )),
    status_anterior text,
    status_novo text,
    resumo text NOT NULL,
    detalhes jsonb NOT NULL DEFAULT '{}'::jsonb,
    registrado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS emenda_historico_emenda_data_idx ON emenda_historico (emenda_id, registrado_em DESC);
CREATE INDEX IF NOT EXISTS emenda_historico_usuario_idx ON emenda_historico (usuario_id, registrado_em DESC) WHERE usuario_id IS NOT NULL;

-- Importações financeiras ficam em lotes separados do cadastro enviado pelos gabinetes.
CREATE TABLE IF NOT EXISTS lotes_financeiros (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem text NOT NULL,
    identificador_externo text,
    referencia_exercicio smallint NOT NULL CHECK (referencia_exercicio >= 2000),
    recebido_em timestamptz NOT NULL DEFAULT now(),
    recebido_por_usuario_id bigint REFERENCES usuarios(id) ON DELETE RESTRICT,
    estado text NOT NULL DEFAULT 'recebido' CHECK (estado IN ('recebido', 'validado', 'rejeitado')),
    hash_arquivo text,
    observacao_validacao text,
    UNIQUE (origem, identificador_externo)
);
CREATE INDEX IF NOT EXISTS lotes_financeiros_estado_data_idx ON lotes_financeiros (estado, recebido_em DESC);
CREATE INDEX IF NOT EXISTS lotes_financeiros_recebedor_idx ON lotes_financeiros (recebido_por_usuario_id) WHERE recebido_por_usuario_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS movimentacoes_financeiras (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id bigint NOT NULL REFERENCES lotes_financeiros(id) ON DELETE RESTRICT,
    emenda_id bigint NOT NULL REFERENCES emendas(id) ON DELETE RESTRICT,
    etapa text NOT NULL CHECK (etapa IN ('autorizado', 'empenhado', 'liquidado', 'pago')),
    valor numeric(14,2) NOT NULL CHECK (valor >= 0),
    codigo_externo text,
    ocorrida_em date,
    registrada_em timestamptz NOT NULL DEFAULT now(),
    UNIQUE (lote_id, emenda_id, etapa, codigo_externo)
);
CREATE INDEX IF NOT EXISTS movimentacoes_emenda_etapa_data_idx ON movimentacoes_financeiras (emenda_id, etapa, ocorrida_em DESC);
CREATE INDEX IF NOT EXISTS movimentacoes_lote_idx ON movimentacoes_financeiras (lote_id);

-- O backend autentica o usuário e define este contexto por transação. Não exponha
-- conexão direta ao banco para os navegadores dos gabinetes.
CREATE OR REPLACE FUNCTION usuario_corrente_id()
RETURNS bigint
LANGUAGE sql
STABLE
AS $$
    SELECT nullif(current_setting('emenda_clara.usuario_id', true), '')::bigint
$$;

CREATE OR REPLACE FUNCTION usuario_tem_perfil(perfis_permitidos text[])
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, emenda_clara
AS $$
    SELECT EXISTS (
        SELECT 1 FROM emenda_clara.usuarios u
        JOIN emenda_clara.usuario_perfis p ON p.usuario_id = u.id
        WHERE u.id = emenda_clara.usuario_corrente_id()
          AND u.ativo
          AND p.perfil = ANY (perfis_permitidos)
    )
$$;

CREATE OR REPLACE FUNCTION usuario_pode_editar_gabinete(gabinete_alvo bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, emenda_clara
AS $$
    SELECT emenda_clara.usuario_tem_perfil(ARRAY['administrador', 'gestao_publica'])
        OR EXISTS (
            SELECT 1 FROM emenda_clara.gabinete_usuarios gu
            JOIN emenda_clara.usuarios u ON u.id = gu.usuario_id
            WHERE gu.gabinete_id = gabinete_alvo
              AND gu.usuario_id = emenda_clara.usuario_corrente_id()
              AND gu.ativo AND u.ativo AND gu.papel IN ('gestor', 'editor')
        )
$$;

CREATE OR REPLACE FUNCTION usuario_pode_ler_emenda(gabinete_alvo bigint, secretaria_alvo bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, emenda_clara
AS $$
    SELECT emenda_clara.usuario_tem_perfil(ARRAY['administrador', 'gestao_publica', 'fazenda', 'controle'])
        OR EXISTS (
            SELECT 1 FROM emenda_clara.gabinete_usuarios gu
            JOIN emenda_clara.usuarios u ON u.id = gu.usuario_id
            WHERE gu.gabinete_id = gabinete_alvo
              AND gu.usuario_id = emenda_clara.usuario_corrente_id()
              AND gu.ativo AND u.ativo
        )
        OR EXISTS (
            SELECT 1 FROM emenda_clara.secretaria_usuarios su
            JOIN emenda_clara.usuarios u ON u.id = su.usuario_id
            WHERE su.secretaria_id = secretaria_alvo
              AND su.usuario_id = emenda_clara.usuario_corrente_id()
              AND su.ativo AND u.ativo
        )
$$;

CREATE OR REPLACE FUNCTION usuario_pode_editar_emenda(gabinete_alvo bigint, secretaria_alvo bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, emenda_clara
AS $$
    SELECT emenda_clara.usuario_pode_editar_gabinete(gabinete_alvo)
        OR emenda_clara.usuario_tem_perfil(ARRAY['administrador', 'gestao_publica'])
        OR EXISTS (
            SELECT 1 FROM emenda_clara.secretaria_usuarios su
            JOIN emenda_clara.usuarios u ON u.id = su.usuario_id
            WHERE su.secretaria_id = secretaria_alvo
              AND su.usuario_id = emenda_clara.usuario_corrente_id()
              AND su.ativo AND u.ativo AND su.papel IN ('gestor', 'analista')
        )
$$;

